#!/usr/bin/env bash
# Prepares a file server for ShareDesk. Run on the server as root:
#   sudo bash setup-host.sh "<contents of id_ed25519.pub>" [/mnt/shares]
# Creates a 'sharedesk' login (key only), installs its public key, and a sudoers file
# listing the commands ShareDesk runs. Safe to re-run.
set -euo pipefail

PUBKEY="${1:?Pass the public key (one line, ssh-ed25519 ...) as the first argument}"
SHARE_ROOT="${2:-/mnt/shares}"
USER_NAME=sharedesk

[ "$(id -u)" -eq 0 ] || { echo "Run as root (sudo)." >&2; exit 1; }
case "$PUBKEY" in ssh-*) ;; *) echo "That doesn't look like an SSH public key." >&2; exit 1 ;; esac

if ! id "$USER_NAME" >/dev/null 2>&1; then
  useradd --system --create-home --shell /bin/bash "$USER_NAME"
fi
passwd -l "$USER_NAME" >/dev/null   # no password login, key only

home="$(getent passwd "$USER_NAME" | cut -d: -f6)"
install -d -m 700 -o "$USER_NAME" -g "$USER_NAME" "$home/.ssh"
printf '%s\n' "$PUBKEY" > "$home/.ssh/authorized_keys"
chown "$USER_NAME:$USER_NAME" "$home/.ssh/authorized_keys"
chmod 600 "$home/.ssh/authorized_keys"
command -v restorecon >/dev/null && restorecon -R "$home/.ssh" || true

bin() { command -v "$1" || { echo "Missing $1" >&2; exit 1; }; }
NET=$(bin net); PDBEDIT=$(bin pdbedit); SMBPASSWD=$(bin smbpasswd); SMBCONTROL=$(bin smbcontrol)
USERADD=$(bin useradd); GROUPADD=$(bin groupadd); GPASSWD=$(bin gpasswd); EXPORTFS=$(bin exportfs)
GETENT=$(bin getent); CAT=$(bin cat); FIND=$(bin find); REALPATH=$(bin realpath); SYSTEMCTL=$(bin systemctl)
DF=$(bin df); TEE=$(bin tee); CP=$(bin cp); MKDIR=$(bin mkdir); CHOWN=$(bin chown); CHMOD=$(bin chmod)

tmp="$(mktemp)"
cat > "$tmp" <<SUDOERS
# ShareDesk (https://github.com/PresWiFi/sharedesk). Generated by setup-host.sh.
# Note: chown/chmod/find/useradd are powerful; treat the sharedesk key as root-equivalent.
Cmnd_Alias SD_READ = $NET conf list, $PDBEDIT -L -v, $GETENT group, $GETENT passwd, \
    $CAT /etc/exports, $CAT /etc/samba/smb.conf, $CAT /etc/exports.d/*.exports, $FIND /etc/exports.d *, $FIND $SHARE_ROOT*, \
    $REALPATH -e -- $SHARE_ROOT*, $SYSTEMCTL is-active *, $DF -B1 --output=size\,used\,avail $SHARE_ROOT
Cmnd_Alias SD_SMB = $NET conf setparm *, $NET conf delparm *, $NET conf addshare *, $NET conf delshare *, \
    $SMBCONTROL smbd reload-config, $SMBPASSWD *
Cmnd_Alias SD_ACCOUNTS = $USERADD --no-create-home --shell /sbin/nologin *, $GROUPADD -- *, $GPASSWD -a *, $GPASSWD -d *
Cmnd_Alias SD_NFS = $TEE /etc/exports, $TEE /etc/exports.d/*.exports, \
    $CP -a -- /etc/exports* /etc/exports*, $EXPORTFS -ra
Cmnd_Alias SD_FILES = $MKDIR -p -- $SHARE_ROOT/*, $CHOWN * -- $SHARE_ROOT*, $CHMOD * -- $SHARE_ROOT*

Defaults:$USER_NAME !requiretty
$USER_NAME ALL=(root) NOPASSWD: SD_READ, SD_SMB, SD_ACCOUNTS, SD_NFS, SD_FILES
SUDOERS

visudo -cf "$tmp" >/dev/null
install -m 440 -o root -g root "$tmp" /etc/sudoers.d/sharedesk
rm -f "$tmp"

echo "Done. ShareDesk can now SSH in as '$USER_NAME' and manage shares under $SHARE_ROOT."
if command -v getenforce >/dev/null && [ "$(getenforce)" = Enforcing ]; then
  echo "SELinux is enforcing: Samba folders need a samba_share_t label (or setsebool -P samba_export_all_rw on)."
fi
